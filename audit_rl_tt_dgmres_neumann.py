"""Read-only evidence audit for the paper-family Neumann experiment.

Only the Python standard library is used. No project package is imported, no
pickle is loaded, and no solve, fit, or inference is performed. The default
requires completed held-out AND historical-paper evaluations. --stage trained
checks training/selection receipts without opening either evaluation's results;
it is explicitly not an effectiveness report. The only write is a new report
file, opened exclusively, never an overwrite of experiment evidence.

This checks saved residual acceptance, not the underlying tensors. Checkpoint
and model files are hash-checked, not executed. NumPy's saved PCG64 bootstrap
interval is range/claim-checked, not independently regenerated by this auditor.
"""
from __future__ import annotations

import argparse
import ast
from collections import Counter, defaultdict
import hashlib
import json
import math
from pathlib import Path, PureWindowsPath
import statistics
import sys


PAPER_SEED = 20260906
DEVELOPMENT_SEEDS = [2026100191, 2026104227, 2026105236, 2026106245]
MODES = ["fixed", "fixed_by_dimension", "rl", "rl_static"]
SOURCE_FOLDERS = ("rl_tt_dgmres_neumann", "rl_tt_dgmres_v1", "rl_tt_dgmres_v2",
                  "rl_tt_dgmres_v3", "adaptive_tt_dgmres", "adaptive_tt_dgmres/backend")
CONTRACT_FIELDS = ("seed", "config", "threads", "features", "actions", "max_states_per_problem",
                   "repeats", "train_dimensions", "paper_protocol", "splits_sha256",
                   "source_sha256", "builder_source", "paper_provenance", "split_contract")
RECOVERY_ACTION = {"update_dim": 24, "matvec_eps": 1e-12, "orth_eps": 1e-12, "solution_eps": 1e-12}


class AuditFailure(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise AuditFailure(message)


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, "Duplicate JSON key: " + str(key))
        result[key] = value
    return result


def read_json(path):
    def bad_constant(value):
        raise AuditFailure("Nonfinite JSON constant: " + value)
    with Path(path).open("r", encoding="utf-8-sig") as handle:
        return json.load(handle, object_pairs_hook=unique_object, parse_constant=bad_constant)


def digest(path):
    value = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            value.update(chunk)
    return value.hexdigest()


def path_key(value):
    return str(PureWindowsPath(str(value))).replace("\\", "/")


def inside(root, relative):
    root = Path(root).resolve()
    name = PureWindowsPath(str(relative))
    require(not name.is_absolute() and not name.drive and ".." not in name.parts,
            "Artifact path escapes declared root: " + str(relative))
    path = root.joinpath(*name.parts).resolve()
    require(root in path.parents, "Artifact must be a file inside its root: " + str(relative))
    return path


def normalized_hashes(mapping):
    require(isinstance(mapping, dict), "Expected artifact/hash map")
    result = {}
    for name, value in mapping.items():
        key = path_key(name)
        require(key not in result, "Duplicate normalized artifact path: " + key)
        require(isinstance(value, str) and len(value) == 64 and
                all(c in "0123456789abcdef" for c in value), "Invalid SHA256: " + key)
        result[key] = value
    return result


def check_hashes(root, mapping, expected=None):
    normalized = normalized_hashes(mapping)
    if expected is not None:
        require(set(normalized) == {path_key(name) for name in expected}, "Incomplete or extra artifact inventory")
    for name, value in normalized.items():
        require(digest(inside(root, name)) == value, "SHA256 mismatch: " + name)
    return normalized


def finite(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def close(left, right):
    return finite(left) and finite(right) and math.isclose(left, right, rel_tol=2e-12, abs_tol=2e-12)


def same(expected, actual, label):
    if isinstance(expected, dict):
        require(isinstance(actual, dict) and set(expected) == set(actual), label + ": keys differ")
        for key in expected:
            same(expected[key], actual[key], label + "/" + str(key))
    elif isinstance(expected, (tuple, list)):
        require(isinstance(actual, (tuple, list)) and len(expected) == len(actual), label + ": length differs")
        for i, (left, right) in enumerate(zip(expected, actual)):
            same(left, right, label + "/" + str(i))
    elif isinstance(expected, float):
        require(close(expected, actual), label + ": numeric value differs")
    else:
        require(type(expected) is type(actual) and expected == actual, label + ": value differs")


def literal_assignment(path, name):
    tree = ast.parse(Path(path).read_text(encoding="utf-8-sig"), filename=str(path))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise AuditFailure("Missing literal source contract: " + name)


def recipe(spec):
    return {"n": spec["n"], "dims": spec["dims"], "seed": spec["seed"],
            "cp_rank": spec["cp_rank"],
            "max_mode": spec["n"] - 1 if spec["max_mode"] is None else spec["max_mode"],
            "null_ratio": float(spec["null_ratio"]), "spectral_decay": float(spec["spectral_decay"]),
            "preparation_tolerance": float(spec["preparation_tolerance"])}


def instance_key(spec):
    encoded = json.dumps(recipe(spec), sort_keys=True, separators=(",", ":"), allow_nan=False)
    return "paper_cp_" + hashlib.sha256(encoded.encode("utf-8")).hexdigest()[:24]


def operator_key(spec):
    # No tensors or project builder: local scalar entries suffice for identity.
    n, d = spec["n"], spec["dims"]
    h = 1.0 / (n - 1)
    scale = h ** (-2)
    norm = d * (2.0 * scale * (1.0 + math.cos(math.pi / n)))
    values = []
    for i in range(n):
        for j in range(n):
            value = ((1.0 if i in (0, n - 1) else 2.0) * scale / norm if i == j
                     else -scale / norm if abs(i - j) == 1 else 0.0)
            values.append(format(value, ".13g") if value != 0 else "0")
    payload = {"n": n, "dims": d, "normalized_local_matrices": [values] * d}
    return "graph_laplacian_" + hashlib.sha256(json.dumps(payload, sort_keys=True).encode("utf-8")).hexdigest()[:24]


def contract(manifest):
    return {name: manifest[name] for name in CONTRACT_FIELDS}


def selection_score(rows, budget):
    return [sum(row["accepted"] for row in rows),
            -math.fsum(row["wall_seconds"] if row["accepted"] else 5 * budget for row in rows)]


def aggregate(rows):
    good = [row for row in rows if row["accepted"]]
    names = {row["problem"]["name"] for row in rows}
    return {"runs": len(rows), "successes": len(good), "instances": len(names),
            "successful_instances_all_repeats": sum(all(r["accepted"] for r in rows
                                                        if r["problem"]["name"] == name) for name in names),
            "median_success_seconds": float(statistics.median(r["wall_seconds"] for r in good)) if good else None,
            "median_success_iterations": float(statistics.median(r["iterations"] for r in good)) if good else None,
            "status_counts": dict(Counter(r["status"] for r in rows)),
            "recoveries": sum(r["recoveries"] for r in rows),
            "shield_interventions": sum(r["shield_interventions"] for r in rows),
            "executed_action_counts": dict(Counter(str(a) for r in rows for a in r["executed_action_indices"]))}


def paired(rows, baseline, candidate, split):
    rows = [r for r in rows if r["split"] == split]
    pairs = []
    for name in sorted({r["problem"]["name"] for r in rows}):
        groups = [[r for r in rows if r["problem"]["name"] == name and r["mode"] == mode]
                  for mode in (baseline, candidate)]
        if not all(groups) or not all(r["accepted"] for group in groups for r in group):
            continue
        first, second = [statistics.median(r["wall_seconds"] for r in group) for group in groups]
        pairs.append({"problem": name, "baseline_seconds": first,
                      "candidate_seconds": second, "speedup": first / second})
    gain = math.exp(math.fsum(math.log(p["speedup"]) for p in pairs) / len(pairs)) if pairs else None
    return {"baseline": baseline, "candidate": candidate, "split": split, "pairs": pairs,
            "common_successful_instances": len(pairs), "geometric_mean_speedup": gain}


class Auditor:
    def __init__(self, output, source_root):
        self.output = Path(output).resolve()
        self.source_root = Path(source_root).resolve()
        self.manifest = read_json(self.output / "manifest.json")
        self.splits = None
        self.baseline = None
        self.fit_records = {}
        self.selections = {}
        self.checked_summaries = 0

    def read(self, relative):
        return read_json(inside(self.output, relative))

    def sha(self, relative):
        return digest(inside(self.output, relative))

    def baseline_for(self, spec):
        return self.manifest["fixed_by_dimension"].get(str(spec["dims"]), self.manifest["best_fixed_index"])

    def check_prepared(self):
        m = self.manifest
        require(m.get("version") == "neumann_1", "Unsupported Neumann protocol version")
        require(type(m["repeats"]) is int and m["repeats"] > 0, "Invalid repetition count")
        require(type(m["threads"]) is int and m["threads"] > 0, "Invalid thread count")
        require(type(m["max_states_per_problem"]) is int and m["max_states_per_problem"] > 0, "Invalid state count")
        config = m["config"]
        for name in ("tolerance", "range_tolerance", "seconds_budget", "failure_penalty", "fixed_round_tolerance",
                     "diagnostic_tolerance", "growth_limit", "projected_check_factor"):
            require(finite(config[name]) and config[name] > 0, "Invalid shared solver parameter: " + name)
        require(type(config["max_iterations"]) is int and config["max_iterations"] >= 2 and
                1 <= config["max_tt_rank"] <= config["recovery_max_tt_rank"] <= config["diagnostic_max_rank"],
                "Invalid common iteration/rank budgets")
        require(self.read("prepared_contract.json") == contract(m), "Prepared experiment contract changed")
        declared = normalized_hashes(m["source_sha256"])
        for root in (self.source_root, self.output / "source_snapshot"):
            files = {path_key(p.relative_to(root)) for folder in SOURCE_FOLDERS for p in (root / folder).glob("*.py")}
            require(files == set(declared), "Current/snapshot source inventory differs from preparation")
            check_hashes(root, declared)
        snapshot = self.output / "source_snapshot"
        require(literal_assignment(snapshot / "rl_tt_dgmres_neumann/problems.py", "BUILDER_SOURCE") == m["builder_source"],
                "Paper builder provenance differs from snapshotted constructor")
        self.paper_source = literal_assignment(snapshot / "rl_tt_dgmres_neumann/problems.py", "PAPER_SOURCE")
        require(len(m["paper_provenance"]) == 2, "Missing paper builder/setup provenance")
        provenance = {}
        for item in m["paper_provenance"]:
            require(self.sha(item["snapshot"]) == item["sha256"], "Paper provenance snapshot changed")
            provenance[PureWindowsPath(item["original_path"]).name] = item
        require(set(provenance) == {"backend_cells.json", "ch05_setup.tex"}, "Unexpected paper provenance sources")
        require(provenance["backend_cells.json"]["sha256"] == m["builder_source"]["sha256"], "Builder SHA differs from paper snapshot")
        require(path_key(provenance["backend_cells.json"]["original_path"]) == path_key(m["builder_source"]["path"]),
                "Builder original path differs from provenance")
        require(path_key(provenance["ch05_setup.tex"]["original_path"]) == path_key(self.paper_source["path"]),
                "Setup source differs from constructor provenance")
        profiles = literal_assignment(snapshot / "rl_tt_dgmres_v2/runner.py", "PROFILES")
        expected_actions = [{"update_dim": length, "matvec_eps": p[0], "orth_eps": p[1], "solution_eps": p[2]}
                            for length in (8, 16, 24) for p in profiles]
        require(len(expected_actions) == 9 and m["actions"] == expected_actions, "Nine-action controls changed")
        base_features = literal_assignment(snapshot / "rl_tt_dgmres_v2/runner.py", "FEATURE_NAMES")
        tree = ast.parse((snapshot / "rl_tt_dgmres_v3/runner.py").read_text(encoding="utf-8-sig"))
        feature_node = next(node.value for node in tree.body if isinstance(node, ast.Assign)
                            and any(isinstance(t, ast.Name) and t.id == "FEATURE_NAMES" for t in node.targets))
        require(isinstance(feature_node, ast.BinOp) and isinstance(feature_node.op, ast.Add), "Unexpected observation schema")
        expected_features = list(base_features) + list(ast.literal_eval(feature_node.right))
        require(m["features"] == expected_features and len(expected_features) == 32, "Observation schema changed")
        require(len(set(expected_features)) == len(expected_features) and
                not any("seed" in name or "reference" in name or "family" in name for name in expected_features),
                "Reference/seed identity exposed as policy feature")
        require(self.sha("splits.json") == m["splits_sha256"], "Prepared split SHA changed")
        splits = self.splits = self.read("splits.json")
        require(set(splits) == {"train", "validation", "test", "paper"}, "Unexpected split roles")
        require({role: len(values) for role, values in splits.items()} == m["split_counts"], "Split counts changed")
        dims = m["train_dimensions"]
        require(dims and len(dims) == len(set(dims)) and all(type(d) is int and d >= 2 for d in dims), "Invalid dimensions")
        names, instances, seeds = set(), set(), set()
        for role, values in splits.items():
            for spec in values:
                require(set(spec) == {"name", "n", "dims", "seed", "cp_rank", "max_mode", "null_ratio",
                                      "spectral_decay", "preparation_tolerance", "family"}, "Unexpected specification fields")
                require(spec["n"] == 12 and spec["cp_rank"] == 3 and spec["null_ratio"] == .1 and
                        spec["spectral_decay"] == 2. and spec["preparation_tolerance"] == 1e-13 and
                        spec["max_mode"] in (None, 11) and spec["family"] == "paper_neumann_poisson_cp", "Not the declared paper construction")
                require(type(spec["seed"]) is int and spec["seed"] >= 0 and type(spec["dims"]) is int and spec["dims"] >= 2,
                        "Invalid numerical construction parameter")
                key = instance_key(spec)
                require(spec["name"] not in names and key not in instances, "Duplicate RHS instance or name across splits")
                names.add(spec["name"]); instances.add(key)
                if role != "paper":
                    require(spec["seed"] != PAPER_SEED and spec["seed"] not in seeds, "RHS seed leakage or historical paper leakage")
                    seeds.add(spec["seed"])
            if role != "paper":
                require({s["dims"] for s in values} == set(dims), "RHS split does not cover configured dimensions")
        paper_dimensions = m["paper_protocol"]["dimensions"]
        require(paper_dimensions and len(set(paper_dimensions)) == len(paper_dimensions) and
                set(paper_dimensions).issubset({4, 5, 6, 10}), "Invalid declared paper dimensions")
        require({(s["dims"], s["seed"]) for s in splits["paper"]} == {(d, PAPER_SEED) for d in paper_dimensions}
                and len(splits["paper"]) == len(paper_dimensions), "Historical showcase differs from declared paper cases")
        declaration = m["split_contract"]
        require(declaration["instance_disjoint"] is True and declaration["operator_disjoint"] is False and
                declaration["paper_seed_excluded_from_training_validation_test"] == PAPER_SEED and
                "same" in declaration["generalization"] and "RHS" in declaration["generalization"], "Misleading split/generalization declaration")
        require(declaration["excluded_development_seeds"] == DEVELOPMENT_SEEDS and
                not seeds.intersection(DEVELOPMENT_SEEDS), "Observed development/pilot RHS leaked into a formal split")
        require({operator_key(s) for s in splits["train"]} == {operator_key(s) for s in splits["test"]},
                "Same-operator claim disagrees with actual normalized matrices")
        for key in ("same_backend", "same_numerical_safeguards", "same_precision_and_budget",
                    "all_online_feature_and_inference_cost_included", "heldout_not_used_for_selection"):
            require(m["acceptance_protocol"][key] is True, "Changed acceptance/fairness contract: " + key)
        require(m["acceptance_protocol"]["training_reference_labels"] is False and
                m["acceptance_protocol"]["primary_baseline"] == "fixed_by_dimension", "Wrong labels or primary comparator")
        paper = m["paper_protocol"]
        expected_tolerances = {"4": 1e-7, "5": 1e-7, "6": 1e-7, "10": 1e-5}
        require(paper["modes"] == ["fixed_by_dimension", "rl"] and paper["repeats"] == m["repeats"] and
                paper["tolerance_by_dimension"] == {str(d): expected_tolerances[str(d)] for d in paper_dimensions}, "Paper protocol changed")

    def check_detail(self, detail, spec, config, *, features=True, kind="fresh", proposed=None):
        row = detail["summary"]
        name = spec["name"]
        require(row["problem"] == spec and row["config"] == config, name + ": problem/config differs")
        require(type(row["accepted"]) is bool and (row["status"] == "eta_target") == row["accepted"], name + ": invalid acceptance/status")
        for key in ("wall_seconds", "total_elapsed_seconds", "checkpoint_elapsed_seconds", "feature_seconds",
                    "input_feature_seconds", "inference_seconds", "final_audit_seconds", "checkpoint_restoration_seconds",
                    "checkpoint_collection_seconds_excluded", "initialization_seconds", "first_initialization_seconds"):
            require(finite(row[key]) and row[key] >= 0, name + ": invalid timing " + key)
        require(row["wall_seconds"] > 0 and close(row["total_elapsed_seconds"], row["wall_seconds"] + row["checkpoint_elapsed_seconds"]),
                name + ": inconsistent episode/checkpoint time")
        require(close(row["remaining_time_budget_at_start"], config["seconds_budget"] - row["checkpoint_elapsed_seconds"]),
                name + ": wrong remaining budget")
        require(row["feature_seconds"] + row["inference_seconds"] + row["final_audit_seconds"] <= row["wall_seconds"] + 1e-8,
                name + ": timed feature/inference/audit costs exceed reported wall time")
        require(row["input_feature_seconds"] <= row["feature_seconds"] + 1e-12, name + ": input feature cost omitted")
        require(type(row["iterations"]) is int and 0 <= row["iterations"] <= config["max_iterations"] and
                type(row["iterations_this_run"]) is int and 0 <= row["iterations_this_run"] <= row["iterations"], name + ": invalid iterations")
        require(row["feature_mode"] == ("online_policy_features" if features else "disabled_fixed_deployment") and
                row["feature_dimension"] == len(self.manifest["features"]), name + ": feature deployment mode/dimension differs")
        require(row["input_feature_extra_matvecs"] == int(features and kind != "branch"), name + ": feature matvec accounting differs")
        if not features:
            require(row["feature_seconds"] == row["input_feature_seconds"] == 0, name + ": fixed baseline computed unused features")
        if kind != "branch":
            require(row["checkpoint_elapsed_seconds"] == row["checkpoint_restoration_seconds"] == 0 and
                    row["iterations_this_run"] == row["iterations"], name + ": fresh solve resumed a checkpoint")
        else:
            require(row["checkpoint_elapsed_seconds"] < config["seconds_budget"] and row["input_feature_seconds"] == 0,
                    name + ": invalid restored checkpoint timing")
        if kind != "collection":
            require(row["checkpoint_collection_seconds_excluded"] == 0, name + ": timed solve excluded collection work")
        if row["accepted"]:
            require(all(finite(row[k]) and row[k] >= 0 for k in
                        ("eta", "range_defect", "relative_transformed_residual", "relative_true_residual")), name + ": accepted invalid residual")
            require(row["eta"] <= config["tolerance"] and row["range_defect"] <= config["range_tolerance"] and
                    row["total_elapsed_seconds"] <= config["seconds_budget"], name + ": accepted beyond common target/budget")
        if row["total_elapsed_seconds"] > config["seconds_budget"]:
            require(not row["accepted"] and row["status"] == "time_budget", name + ": overtime status differs")
        require(row["acceptance"] == "independent_untruncated_float64_transformed_eta_and_range_not_interval_bound" and
                row["numerical_engine"] == "v2_kernels_v3_single_cycle_scheduler_shared_by_all_policies", name + ": backend/acceptance changed")
        cycles = detail["cycles"]
        require(row["cycles"] == len(cycles) and row["action_indices"] == [c["action"] for c in cycles] and
                row["executed_action_indices"] == [c["executed_action"] for c in cycles], name + ": cycle/action history inconsistent")
        require(row["recoveries"] == len(detail["recoveries"]) and row["breakdown_restarts"] == len(detail["breakdown_restarts"]),
                name + ": recovery/restart count differs")
        interventions = 0
        for cycle in cycles:
            require(type(cycle["action"]) is int and 0 <= cycle["action"] < 9 and
                    type(cycle["executed_action"]) is int and -1 <= cycle["executed_action"] < 9, name + ": invalid action")
            executed = cycle["executed_action"]
            controls = RECOVERY_ACTION if executed == -1 else self.manifest["actions"][executed]
            require(cycle["controls"] == controls, name + ": executed controls differ from action or recovery")
            require(config["max_tt_rank"] <= cycle["rank_cap"] <= config["recovery_max_tt_rank"], name + ": rank cap out of shared bounds")
            eps = min(config["fixed_round_tolerance"], controls["matvec_eps"]) if executed == -1 else config["fixed_round_tolerance"]
            require(cycle["residual_eps"] == cycle["transformed_eps"] == eps, name + ": undocumented residual precision override")
            require(len(cycle["state"]) == len(self.manifest["features"]) and all(finite(v) for v in cycle["state"]), name + ": invalid online observation")
            if not features:
                require(all(v == 0 for v in cycle["state"]), name + ": fixed state is not feature-disabled")
            if proposed is not None:
                require(cycle["action"] == proposed, name + ": fixed proposal changed")
            interventions += executed != cycle["action"]
        require(row["shield_interventions"] >= interventions, name + ": missing shield accounting")
        if kind != "branch":
            require(row["shield_interventions"] == interventions, name + ": fresh shield count differs")
        if cycles:
            require(close(math.fsum(c["seconds"] for c in cycles), row["wall_seconds"]), name + ": cycle time excludes overhead")
            require(close(row["reward_sum"], -row["wall_seconds"] / config["seconds_budget"] -
                          (0 if row["accepted"] else config["failure_penalty"])), name + ": cost/reward semantics differ")
        self.checked_summaries += 1
        return row

    def check_baselines(self):
        m = self.manifest
        specs = self.splits["validation"]
        protocol = self.read("fixed_protocol.json")
        require(protocol == {"contract": contract(m), "validation_specs": specs, "actions": list(range(9)),
                             "compute_policy_features": False}, "Fixed grid protocol differs")
        require(self.sha("baseline_validation.json") == m["baseline_validation_sha256"], "Fixed grid SHA differs")
        grid = self.read("baseline_validation.json")
        require([g["action"] for g in grid] == list(range(9)), "Incomplete nine-action fixed grid")
        for item in grid:
            rows = [self.check_detail(self.read(f"fixed_validation/{s['name']}_a{item['action']}.json"), s,
                                     m["config"], features=False, proposed=item["action"]) for s in specs]
            require(item["rows"] == rows, "Fixed grid rows differ from raw results")
            same(selection_score(rows, m["config"]["seconds_budget"]), item["score"], "global fixed validation score")
            scores = {str(d): selection_score([r for r in rows if r["problem"]["dims"] == d], m["config"]["seconds_budget"])
                      for d in m["train_dimensions"]}
            same(scores, item["dimension_scores"], "per-dimension fixed validation score")
        best = max(grid, key=lambda g: tuple(g["score"]))["action"]
        dimensions = {str(d): max(grid, key=lambda g: tuple(g["dimension_scores"][str(d)]))["action"] for d in m["train_dimensions"]}
        require(m["best_fixed_index"] == best and m["fixed_by_dimension"] == dimensions, "Fixed baselines are not validation-grid winners")
        self.baseline = {"global": best, "by_dimension": dimensions, "validation_sha256": m["baseline_validation_sha256"]}

    def check_fit(self, iteration):
        m = self.manifest
        prefix = f"rollouts_{iteration}"
        target = "baseline" if iteration == 0 else f"policy_iteration_{iteration}"
        protocol = self.read(prefix + "/collection_protocol.json")
        require(protocol["continuation_policy"] == target and protocol["baseline"] == self.baseline and
                protocol["source_sha256"] == m["source_sha256"] and protocol["config"] == m["config"] and
                protocol["specs"] == self.splits["train"] and protocol["candidate_actions"] == list(range(9)) and
                protocol["max_states"] == m["max_states_per_problem"], "Collection differs from prepared real-rollout protocol")
        previous = None if iteration == 0 else self.read(f"selection_{iteration - 1}.json")
        require(protocol["selection"] == previous, "Training continuation differs from previous selected policy")
        summary = self.read(prefix + "/summary.json")
        rows = self.read(prefix + "/rows.json")
        require(summary["complete"] is True and summary["problems"] == len(self.splits["train"]) and
                summary["rows"] == len(rows) and rows and summary["continuation_policy"] == target,
                "Fit requires complete nonempty training collection")
        require(summary["rows_sha256"] == self.sha(prefix + "/rows.json"), "Training row SHA changed")
        check_hashes(self.output, summary["raw_files_sha256"], [r["source"] for r in rows])
        require(len({path_key(r["source"]) for r in rows}) == len(rows), "Training raw source reused across rows")
        expected_receipts = [prefix + "/" + s["name"] + "_states_receipt.json" for s in self.splits["train"]]
        check_hashes(self.output, summary["state_receipts_sha256"], expected_receipts)
        by_name = {s["name"]: s for s in self.splits["train"]}
        for spec in self.splits["train"]:
            stem = prefix + "/" + spec["name"]
            receipt = self.read(stem + "_states_receipt.json")
            require(self.sha(stem + "_states.pt") == receipt["checkpoint_sha256"] and
                    self.sha(stem + "_collection.json") == receipt["trajectory_sha256"], "Real trajectory/checkpoint changed")
            self.check_detail(self.read(stem + "_collection.json"), spec, m["config"], kind="collection",
                              proposed=self.baseline_for(spec) if iteration == 0 else None)
        groups, state_indices, records = defaultdict(list), defaultdict(set), []
        for row in rows:
            spec = by_name.get(row["problem_id"])
            require(spec is not None and spec["seed"] != PAPER_SEED and row["split"] == "train" and
                    row["data_origin"] == "real_rollout" and row["continuation_policy"] == target, "Nontraining or invented return in fit")
            require(row["instance_key"] == instance_key(spec) and row["operator_group_key"] == operator_key(spec) and
                    row["baseline_index"] == self.baseline_for(spec), "Rollout instance/operator/baseline mismatch")
            require(row["time_budget"] == m["config"]["seconds_budget"] and
                    row["cost_semantics"] == "remaining_wall/original_episode_budget + failure_penalty", "Wrong training cost normalization")
            require(type(row["state_index"]) is int and 0 <= row["state_index"] < m["max_states_per_problem"] and
                    row["state_id"] == f"{target}/{spec['name']}/{row['state_index']}", "Invalid checkpoint state identity")
            expected_source = f"{prefix}/{spec['name']}_s{row['state_index']}_a{row['action']}.json"
            require(path_key(row["source"]) == expected_source, "Branch raw path differs from its state/action")
            raw = self.read(row["source"])
            require(raw["row"] == row, "Training row differs from raw return")
            detail = self.check_detail(raw["detail"], spec, m["config"], kind="branch")
            require(row["remaining_wall"] == detail["wall_seconds"] and row["success"] == detail["accepted"] and
                    type(row["success"]) is bool and row["checkpoint_elapsed_seconds"] == detail["checkpoint_elapsed_seconds"],
                    "Training label/time differs from actual branch")
            require(row["executed_first_action"] == (detail["executed_action_indices"][0] if detail["executed_action_indices"] else None),
                    "First executed action differs from saved rollout")
            if detail["action_indices"]:
                require(detail["action_indices"][0] == row["action"], "Candidate branch was not proposed first")
                if iteration == 0:
                    require(all(a == self.baseline_for(spec) for a in detail["action_indices"][1:]), "Wrong baseline continuation")
            require(type(row["action"]) is int and 0 <= row["action"] < 9 and len(row["features"]) == len(m["features"]) and
                    all(finite(v) for v in row["features"]), "Invalid training action/features")
            groups[row["state_id"]].append(row)
            state_indices[spec["name"]].add(row["state_index"])
            cost = row["remaining_wall"] / row["time_budget"] + m["config"]["failure_penalty"] * float(not row["success"])
            records.append({"features": [float(v) for v in row["features"]], "action": row["action"], "cost_target": cost,
                            "failure_target": float(not row["success"]),
                            "group": json.dumps([str(row["problem_id"]), str(row["state_id"])], ensure_ascii=False),
                            "source": str(row["source"])})
        require(summary["states"] == len(groups) and summary["successes"] == sum(r["success"] for r in rows), "Collection totals differ")
        for state_rows in groups.values():
            require(sorted(r["action"] for r in state_rows) == list(range(9)), "A checkpoint lacks exactly all nine branches")
            require(all(r["features"] == state_rows[0]["features"] and
                        r["checkpoint_elapsed_seconds"] == state_rows[0]["checkpoint_elapsed_seconds"] for r in state_rows),
                    "Candidate actions did not share the same recorded checkpoint")
        for indices in state_indices.values():
            require(indices == set(range(len(indices))), "Sampled state indices have gaps")
        fit_protocol = self.read(f"fit_protocol_{iteration}.json")
        require(fit_protocol["rows_sha256"] == self.sha(prefix + "/rows.json") and
                fit_protocol["collection_summary_sha256"] == self.sha(prefix + "/summary.json") and
                fit_protocol["target_policy"] == target and fit_protocol["source_sha256"] == m["source_sha256"] and
                fit_protocol["baseline"] == self.baseline and fit_protocol["generalization"] == m["split_contract"]["generalization"],
                "Fitted model no longer matches real training data contract")
        fit_config = fit_protocol["config"]
        require(fit_config["n_actions"] == 9 and fit_config["failure_penalty"] == m["config"]["failure_penalty"] and
                fit_config["seed"] == m["seed"] + iteration, "Fit action/cost/seed contract differs")
        fit = self.read(f"fit_{iteration}.json")
        require(fit["model_sha256"] == self.sha(f"controller_iteration_{iteration}.pt") and fit["target_policy"] == target,
                "Model differs from its fitted artifact")
        result = fit["result"]
        record_digest = hashlib.sha256(json.dumps(records, sort_keys=True, ensure_ascii=False, allow_nan=False).encode("utf-8")).hexdigest()
        require(result["training_rows_sha256"] == record_digest, "Fitted cost/failure/feature target digest differs from real returns")
        require(result["fit_call"] == 1 and result["rows"] == len(rows) and result["input_dim"] == len(m["features"]) and result["target_policy"] == target and
                result["bootstrap_groups"] == len(groups) and result["failure_count"] == sum(not r["success"] for r in rows) and
                result["action_counts"] == [sum(r["action"] == a for r in rows) for a in range(9)] and
                result["epochs"] == fit_config["epochs"] and result["warm_start"] is False and result["scaler_refitted"] is True,
                "Fit receipt dimensions, targets or training-only scaler changed")
        expected_pairs = sum(sum(r["success"] for r in group) * (sum(r["success"] for r in group) - 1) // 2 for group in groups.values())
        require(result["successful_action_pairs"] == expected_pairs and len(result["members"]) == fit_config["ensemble_size"],
                "Fit pairwise/ensemble accounting differs")
        require(len(result["source_data"]) == 1 and
                PureWindowsPath(result["source_data"][0]).parts[-2:] == (prefix, "rows.json"), "Fit source-data receipt points elsewhere")
        for member_index, member in enumerate(result["members"]):
            require(member["member"] == member_index and member["bootstrap_rows"] == len(rows) and
                    type(member["updates"]) is int and member["updates"] > 0 and finite(member["loss_last"]),
                    "Fit receipt lacks finite actual ensemble optimization")
        require(finite(fit["seconds"]) and fit["seconds"] >= 0, "Invalid fitting time")
        self.fit_records[iteration] = {"rows": len(rows), "states": len(groups), "successes": summary["successes"],
                                       "problems_with_branch_labels": len(state_indices),
                                       "model_sha256": fit["model_sha256"], "fit_seconds": fit["seconds"]}

    def check_selection(self, iteration):
        m = self.manifest
        require(iteration in self.fit_records, "Selection refers to unaudited fitted model")
        protocol = self.read(f"validation_protocol_{iteration}.json")
        require(protocol["specs"] == self.splits["validation"] and protocol["config"] == m["config"] and
                protocol["source_sha256"] == m["source_sha256"], "Validation protocol changed")
        grid = self.read(f"validation_{iteration}.json")
        require(len(grid) == len(protocol["selections"]) == 3 and [g["gate_index"] for g in grid] == [0, 1, 2], "Validation gate grid incomplete")
        for item, declared in zip(grid, protocol["selections"]):
            require({k: item[k] for k in declared} == declared and item["baselines"] == self.baseline and
                    item["iteration"] == iteration and item["model"] == f"controller_iteration_{iteration}.pt" and
                    item["model_sha256"] == self.fit_records[iteration]["model_sha256"], "Validation candidate differs from fit/baseline")
            paths = [f"validation_{iteration}/{s['name']}_g{item['gate_index']}.json" for s in self.splits["validation"]]
            check_hashes(self.output, item["validation_file_sha256"], paths)
            rows = [self.check_detail(self.read(p), s, m["config"]) for p, s in zip(paths, self.splits["validation"])]
            require(item["rows"] == rows and all(r["forward_error"] is None for r in rows), "Validation rows/reference exclusion differ")
            same(selection_score(rows, m["config"]["seconds_budget"]), item["score"], "learned validation score")
        winner = max(grid, key=lambda row: tuple(row["score"]))
        saved = self.read(f"selection_{iteration}.json")
        require(saved == {k: v for k, v in winner.items() if k != "rows"}, "Selected gate is not validation winner")
        self.selections[iteration] = saved

    def check_training(self):
        fit_paths = sorted(self.output.glob("fit_[0-9]*.json"))
        require(fit_paths, "No completed fitted artifact; --stage trained requires at least one fit")
        iterations = sorted(int(p.stem.split("_")[-1]) for p in fit_paths)
        require(iterations == list(range(len(iterations))), "Missing policy-iteration fit receipt")
        for iteration in iterations:
            self.check_fit(iteration)
            if (self.output / f"selection_{iteration}.json").exists():
                self.check_selection(iteration)
            if iteration < iterations[-1]:
                require(iteration in self.selections, "Policy improvement lacks previous validation selection")
        require({p.name for p in self.output.glob("controller_iteration_*.pt")} ==
                {f"controller_iteration_{i}.pt" for i in iterations}, "Unreceipted model artifact")
        require({p.name for p in self.output.glob("selection_*.json")} ==
                {f"selection_{i}.json" for i in self.selections}, "Unreceipted selection artifact")

    def check_frozen(self):
        m = self.manifest
        require(self.selections, "Frozen run has no validation-selected model")
        require(self.sha("frozen_selection.json") == m["frozen_selection_sha256"], "Frozen receipt SHA changed")
        receipt = self.read("frozen_selection.json")
        selection_files = sorted(self.output.glob("selection_*.json"))
        check_hashes(self.output, receipt["selection_files_sha256"], [p.name for p in selection_files])
        winner = max((self.read(p.name) for p in selection_files), key=lambda row: tuple(row["score"]))
        require(receipt["selection"] == m["selected"] == winner and receipt["baseline"] == self.baseline and
                receipt["contract"] == contract(m) and receipt["evaluation_modes"] == m["evaluation_modes"] == MODES,
                "Frozen policy/config differs from validation winner")
        require(m["selected_model_sha256"] == winner["model_sha256"] == self.sha(winner["model"]), "Frozen model SHA differs")

    def check_decisions(self, detail, spec, mode):
        decisions = detail.get("decisions", [])
        cycles = detail["cycles"]
        if mode in {"fixed", "fixed_by_dimension"}:
            require(not decisions, "Fixed baseline contains learned decisions")
            return
        require(len(decisions) == (min(1, len(cycles)) if mode == "rl_static" else len(cycles)), "Missing/extra learned decisions")
        actions = [c["action"] for c in cycles]
        if mode == "rl_static":
            require(len(set(actions)) <= 1, "Static controller changed its proposed action")
        for i, decision in enumerate(decisions):
            require(decision["action"] == actions[i] and decision["baseline_action"] == self.baseline_for(spec) and
                    decision["gate"] == self.manifest["selected"]["gate"] and
                    decision["guarantees_wallclock_improvement"] is False and
                    decision["prediction"]["uncertainty_is_certified"] is False, "Policy decision/baseline/evidence boundary differs")
            require(decision["prediction"]["target_policy"] == ("baseline" if self.manifest["selected"]["iteration"] == 0
                    else f"policy_iteration_{self.manifest['selected']['iteration']}"), "Wrong fitted continuation target")

    def check_evaluation(self, paper=False):
        m = self.manifest
        split = "paper" if paper else "test"
        folder = "paper_evaluation" if paper else "evaluation"
        summary_file = "paper_summary.json" if paper else "evaluation_summary.json"
        specs = self.splits[split]
        modes = m["paper_protocol"]["modes"] if paper else MODES
        repeats = m["paper_protocol"]["repeats"] if paper else m["repeats"]
        require(self.read(folder + "/protocol.json") == {"contract": contract(m), "frozen_sha256": m["frozen_selection_sha256"],
                "specs": specs, "modes": modes, "repeats": repeats, "paper": paper}, "Evaluation protocol changed")
        receipt = self.read(folder + "/completed_receipt.json")
        require(receipt["summary_sha256"] == self.sha(summary_file) and
                receipt["protocol_sha256"] == self.sha(folder + "/protocol.json") and
                receipt["frozen_selection_sha256"] == m["frozen_selection_sha256"], "Completed evaluation receipt changed")
        expected = {(s["name"], mode, r) for s in specs for mode in modes for r in range(repeats)}
        paths = [f"{folder}/{split}/{name}_{mode}_r{repeat}.json" for name, mode, repeat in expected]
        check_hashes(self.output, receipt["raw_files_sha256"], paths)
        actual_paths = {path_key(p.relative_to(self.output)) for p in (self.output / folder / split).glob("*.json")}
        require(actual_paths == set(paths), "Extra or missing raw evaluation files")
        rows = self.read(summary_file)
        keys = [(r["problem"]["name"], r["mode"], r["repeat"]) for r in rows]
        require(len(keys) == len(expected) and set(keys) == expected, "Evaluation repetitions missing/extra/duplicated")
        by_name = {s["name"]: s for s in specs}
        fingerprints = defaultdict(set)
        for row, (name, mode, repeat) in zip(rows, keys):
            spec = by_name[name]
            require(row["split"] == split and row["instance_key"] == instance_key(spec) and
                    row["baseline_index"] == self.baseline_for(spec), "Evaluation instance/baseline differs")
            config = dict(m["config"])
            if paper:
                config.update(tolerance=m["paper_protocol"]["tolerance_by_dimension"][str(spec["dims"])],
                              seconds_budget=m["paper_protocol"]["seconds_budget"])
            detail = self.read(f"{folder}/{split}/{name}_{mode}_r{repeat}.json")
            proposed = m["best_fixed_index"] if mode == "fixed" else self.baseline_for(spec) if mode == "fixed_by_dimension" else None
            actual = self.check_detail(detail, spec, config, features=mode not in {"fixed", "fixed_by_dimension"}, proposed=proposed)
            require(actual == row, "Raw evaluation summary differs from aggregate")
            if row["accepted"]:
                require(finite(row["forward_error"]) and row["forward_error"] >= 0, "Successful showcase/test lacks finite reference diagnostic")
            metadata = detail["construction_metadata"]
            require(metadata["instance_key"] == instance_key(spec) and metadata["construction_parameters"] == recipe(spec) and
                    metadata["operator_group_key"] == operator_key(spec) and metadata["builder_source"] == m["builder_source"] and
                    metadata["paper_source"] == self.paper_source and
                    metadata["reference_in_online_view"] is False and metadata["preparation"]["rank_cap"] is None and
                    metadata["preparation"]["relative_tolerance"] == 1e-13 and metadata["preparation"]["ab_is_unrounded"] is True,
                    "Evaluation construction differs from paper recipe/provenance")
            fingerprints[operator_key(spec)].add(metadata["operator_fingerprint"])
            self.check_decisions(detail, spec, mode)
        require(all(len(values) == 1 for values in fingerprints.values()), "Same normalized operator has inconsistent fingerprints")
        return rows

    def check_reports(self, rows, paper_rows):
        m = self.manifest
        grouped = {mode: aggregate([r for r in rows if r["mode"] == mode]) for mode in MODES}
        by_dimension = {str(d): {mode: aggregate([r for r in rows if r["problem"]["dims"] == d and r["mode"] == mode])
                                 for mode in MODES} for d in m["train_dimensions"]}
        same(grouped, self.read("aggregate.json"), "test aggregates")
        same(by_dimension, self.read("aggregate_by_dimension.json"), "dimension aggregates")
        pairs = [paired(rows, baseline, candidate, "test") for baseline, candidate in
                 (("fixed_by_dimension", "rl"), ("fixed", "rl"), ("fixed_by_dimension", "rl_static"), ("rl_static", "rl"))]
        saved = self.read("paired_speedups.json")
        require(len(saved) == len(pairs), "Missing paired comparison")
        for actual, item in zip(pairs, saved):
            same(actual, {k: v for k, v in item.items() if k != "bootstrap_95_percent_interval"}, "paired medians/geometric speedup")
            interval = item.get("bootstrap_95_percent_interval")
            if actual["pairs"]:
                require(isinstance(interval, list) and len(interval) == 2 and all(finite(v) and v > 0 for v in interval)
                        and interval[0] <= interval[1], "Invalid saved bootstrap interval")
                extrema = [p["speedup"] for p in actual["pairs"]]
                require(min(extrema) - 1e-12 <= interval[0] <= interval[1] <= max(extrema) + 1e-12,
                        "Saved bootstrap interval outside possible instance-resampling range")
            else:
                require(interval is None, "Bootstrap interval without any paired instances")
        gain = pairs[0]["geometric_mean_speedup"]
        evidence = {"primary_baseline": "fixed_by_dimension",
                    "success_count_no_lower": grouped["rl"]["successes"] >= grouped["fixed_by_dimension"]["successes"],
                    "paired_speedup_above_one": gain is not None and gain > 1,
                    "paired_ci_lower_above_one": saved[0].get("bootstrap_95_percent_interval", [0])[0] > 1,
                    "success_rate_statistical_noninferiority_proven": False,
                    "operator_disjoint": False, "scope": m["split_contract"]["generalization"]}
        require(self.read("claim_audit.json") == evidence, "Claim flags disagree with success counts/paired timing or overstate inference")
        paper = self.read("paper_report.json")
        require(paper["rows"] == paper_rows and paper["protocol"] == m["paper_protocol"] and
                paper["known_historical_cases_not_heldout"] is True and paper["never_used_for_selection"] is True and
                paper["source_seed"] == PAPER_SEED and paper["purpose"] == m["paper_protocol"]["purpose"], "Paper showcase confused with held-out evidence")
        paper_pairs = paired(paper_rows, "fixed_by_dimension", "rl", "paper")
        same(paper_pairs, paper["paired_speedups"], "paper paired timing")
        same({mode: aggregate([r for r in paper_rows if r["mode"] == mode]) for mode in m["paper_protocol"]["modes"]},
             paper["aggregates"], "paper aggregates")
        require((self.output / "REPORT.md").is_file(), "Missing completed narrative report")
        return {"aggregates": grouped, "aggregates_by_dimension": by_dimension, "paired_speedups": pairs,
                "claim_consistency": evidence, "primary_observed_claim_met": evidence["success_count_no_lower"] and evidence["paired_speedup_above_one"],
                "paper_aggregates": paper["aggregates"], "paper_paired_speedups": paper_pairs,
                "bootstrap_check": "saved interval schema, attainable range and claim flags only; NumPy PCG64 draws not independently regenerated"}

    def run(self, stage):
        m = self.manifest
        if stage == "complete":
            require(m.get("stage") == "complete" and m.get("evaluation_started") is True and
                    m.get("paper_started") is True and m.get("paper_complete") is True,
                    "Full audit requires completed test AND paper evaluation; no held-out rows opened")
        self.check_prepared()
        self.check_baselines()
        self.check_training()
        frozen = (self.output / "frozen_selection.json").exists()
        if frozen:
            self.check_frozen()
        else:
            require(stage == "trained" and not m.get("evaluation_started") and not m.get("paper_started") and
                    m.get("stage") not in {"frozen", "evaluating", "complete"}, "Evaluation without a verified frozen selection")
        result = {"audit_passed": True, "requested_stage": stage, "manifest_stage": m["stage"],
                  "partial_training_audit": stage == "trained", "effectiveness_evaluated": stage == "complete",
                  "output": str(self.output), "manifest_sha256": self.sha("manifest.json"),
                  "prepared_contract_sha256": self.sha("prepared_contract.json"),
                  "auditor_sha256": digest(Path(__file__)), "baseline": self.baseline,
                  "fitted_iterations": {str(k): v for k, v in self.fit_records.items()},
                  "frozen_selection_verified": frozen,
                  "limitations": ["Hash-linked evidence consistency, not a cryptographic external timestamp or proof of historical execution.",
                                  "Models and tensor checkpoints are hash-checked without unpickling or executing them.",
                                  "Saved independent float64 acceptance is checked; residual tensors are not recomputed.",
                                  "Training and test share operators; only new RHS instances are held out.",
                                  "Known paper seed cases are descriptive showcases, excluded from held-out claims.",
                                  "An observed fixed-versus-RL gain alone does not establish cycle-by-cycle adaptation benefit; rl_static is a separate comparator.",
                                  "Gate disagreement and failure penalties are not convergence or universal acceleration proofs."]}
        if stage == "complete":
            require(frozen, "Completed evaluation lacks frozen selection")
            result.update(self.check_reports(self.check_evaluation(), self.check_evaluation(paper=True)))
        else:
            result["effectiveness_claim"] = "Not evaluated: this stage never opens test or paper result files."
        result["checked_raw_summaries"] = self.checked_summaries
        return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, help="Existing experiment run directory; read only")
    parser.add_argument("--report", required=True, help="New JSON audit report path; never overwritten")
    parser.add_argument("--stage", choices=("complete", "trained"), default="complete")
    parser.add_argument("--source-root", default=str(Path(__file__).resolve().parent), help="Current source root to compare with frozen snapshots")
    args = parser.parse_args(argv)
    report_path = Path(args.report).resolve()
    if report_path.exists():
        parser.error("--report must be a new file; existing evidence is never overwritten")
    try:
        result = Auditor(args.output, args.source_root).run(args.stage)
    except (AuditFailure, OSError, KeyError, IndexError, AttributeError, TypeError, ValueError,
            ArithmeticError, StopIteration, SyntaxError) as exc:
        result = {"audit_passed": False, "requested_stage": args.stage,
                  "effectiveness_evaluated": False, "error": str(exc), "error_type": type(exc).__name__}
    try:
        with report_path.open("x", encoding="utf-8") as handle:
            json.dump(result, handle, ensure_ascii=False, indent=2, allow_nan=False)
            handle.write("\n")
    except OSError as exc:
        print("Cannot create new audit report: " + str(exc), file=sys.stderr)
        return 2
    print(json.dumps({"audit_passed": result["audit_passed"], "stage": args.stage,
                      "report": str(report_path), "error": result.get("error")}, ensure_ascii=False))
    return 0 if result["audit_passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
